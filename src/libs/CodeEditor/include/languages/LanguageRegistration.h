/**
 * @brief Явный "hook", гарантирующий регистрацию всех языков.
 *
 * CodeEditor собирается как статическая библиотека (add_library(... STATIC)).
 * Ни один языковой .cpp-файл в src/languages/ не экспортирует символ, на
 * который где-либо есть прямая ссылка — регистрация раньше происходила
 * только через побочный эффект статического конструктора
 * (см. CREMNIY_REGISTER_LANGUAGE в LanguageRegistry.h). Для линкера
 * статической библиотеки такой файл выглядит неиспользуемым, и он вправе
 * (и на части линковщиков/платформ действительно будет) выбросить его
 * object-файл из финального бинарника целиком — из-за чего язык окажется
 * не зарегистрирован в рантайме без единой ошибки компиляции или линковки.
 *
 * registerAllLanguages() устраняет эту зависимость от поведения линкера:
 * она напрямую вызывает "forceLink"-функцию каждого языка (сгенерированную
 * макросом CREMNIY_REGISTER_LANGUAGE), поэтому у линкера появляется явная
 * причина включить каждый .o-файл. Вызывается один раз, явно, из main(),
 * до создания первого окна редактора (см. src/main.cpp).
 *
 * При добавлении нового языка: добавь ОДНУ строку в
 * src/languages/core/LanguageRegistration.cpp (см. комментарий в этом файле).
 * Это единственное отступление от "просто добавь новый .cpp-файл",
 * необходимое из-за особенностей статической линковки; вся остальная
 * структура (один файл на язык, никаких правок CustomCodeEditor.cpp)
 * остаётся в силе. Подробнее — docs/adding_a_language.md.
 */
